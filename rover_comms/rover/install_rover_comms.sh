#!/usr/bin/env bash
# install_rover_comms.sh — set up the rover side of the desktop<->rover link.
# Idempotent: safe to re-run. Run ON the rover from the repo:
#
#     cd ~/isaac-assets/rover_comms/rover
#     ./install_rover_comms.sh
#
# What it does:
#   1. Removes the old broken Fast DDS initial-peers profile from ~/.bashrc and
#      (if present) /usr/local/bin/start_ugv_driver.sh — that profile is what
#      isolated nodes.
#   2. Installs rover_env.sh to /usr/local/lib/rover_comms/ and the rover-*
#      helper scripts to /usr/local/bin.
#   3. Installs the rover-comms-bringup systemd service (templated to this user).
#   4. Optionally installs Tailscale (far mode).
#
# It does NOT build the workspace or install ROS — use jetson_rover_setup for
# that first if the rover isn't set up yet.
set -eo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# repo root = two levels up (…/rover_comms/rover -> repo root), wherever cloned
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
LIB_DIR=/usr/local/lib/rover_comms
BIN_DIR=/usr/local/bin

echo "== rover_comms installer =="
echo "source:    ${SCRIPT_DIR}"
echo "repo root: ${REPO_ROOT}"

# --- 1. scrub the old broken profile ----------------------------------------
echo "-- removing old FASTRTPS_DEFAULT_PROFILES_FILE references"
if grep -q 'FASTRTPS_DEFAULT_PROFILES_FILE' "$HOME/.bashrc" 2>/dev/null; then
  cp "$HOME/.bashrc" "$HOME/.bashrc.rovercomms.bak.$(date +%Y%m%d_%H%M%S)"
  sed -i '/FASTRTPS_DEFAULT_PROFILES_FILE/d' "$HOME/.bashrc"
  echo "   cleaned ~/.bashrc (backup made)"
fi
if [ -f /usr/local/bin/start_ugv_driver.sh ] && \
   grep -q 'FASTRTPS_DEFAULT_PROFILES_FILE' /usr/local/bin/start_ugv_driver.sh 2>/dev/null; then
  sudo cp /usr/local/bin/start_ugv_driver.sh "/usr/local/bin/start_ugv_driver.sh.bak.$(date +%Y%m%d_%H%M%S)"
  sudo sed -i '/FASTRTPS_DEFAULT_PROFILES_FILE/d' /usr/local/bin/start_ugv_driver.sh
  echo "   cleaned /usr/local/bin/start_ugv_driver.sh (backup made)"
fi

# --- 2. install env + helper scripts ----------------------------------------
echo "-- installing rover_env.sh + watchdog node -> ${LIB_DIR}"
sudo install -d "${LIB_DIR}"
sudo install -m 0644 "${SCRIPT_DIR}/rover_env.sh" "${LIB_DIR}/rover_env.sh"
sudo install -m 0644 "${SCRIPT_DIR}/watchdog/cmd_vel_watchdog.py" "${LIB_DIR}/cmd_vel_watchdog.py"

echo "-- installing helpers -> ${BIN_DIR}"
for s in rover-env rover-mode rover-bringup rover-verify rover-teleop-test \
         rover-cmdvel-watchdog rover-wifi-join; do
  sudo install -m 0755 "${SCRIPT_DIR}/bin/${s}" "${BIN_DIR}/${s}"
  echo "   ${BIN_DIR}/${s}"
done
# (helpers auto-resolve ${LIB_DIR}/rover_env.sh via their built-in fallback path)

# --- 3. default mode + config dir + repo paths ------------------------------
CFG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/rover_comms"
mkdir -p "${CFG_DIR}"
if [ ! -f "${CFG_DIR}/mode" ]; then
  echo "far" > "${CFG_DIR}/mode"
  echo "-- default mode set to 'far' (${CFG_DIR}/mode) — change with: rover-mode near"
fi
# record where the repo/workspace live so the installed env finds them anywhere
cat > "${CFG_DIR}/paths.env" <<EOF
# auto-generated by install_rover_comms.sh — where this rover's repo lives
ISAAC_ASSETS_DIR=${REPO_ROOT}
UGV_WS=${REPO_ROOT}/ugv_ws
EOF
echo "-- recorded repo paths -> ${CFG_DIR}/paths.env"

# --- 4. systemd service ------------------------------------------------------
echo "-- installing systemd unit rover-comms-bringup.service"
tmp="$(mktemp)"
sed -e "s#__ROVER_USER__#${USER}#g" -e "s#__ROVER_HOME__#${HOME}#g" \
  "${SCRIPT_DIR}/systemd/rover-comms-bringup.service" > "${tmp}"
sudo install -m 0644 "${tmp}" /etc/systemd/system/rover-comms-bringup.service
rm -f "${tmp}"
sudo systemctl daemon-reload
echo "   installed. NOTE: if ugv-bringup.service is enabled, disable it so only"
echo "   one driver runs:  sudo systemctl disable --now ugv-bringup.service"

# --- 5. optional Tailscale ---------------------------------------------------
echo
read -r -p "Install/join Tailscale now for far mode? [y/N] " ans || ans=n
case "${ans}" in
  y|Y) "${SCRIPT_DIR}/tailscale_up.sh" ;;
  *)   echo "Skipped Tailscale. For far mode run ./tailscale_up.sh later." ;;
esac

cat <<EOF

== Done ==
Baseline: ROS_DOMAIN_ID=0, rmw_fastrtps_cpp, ROS_LOCALHOST_ONLY=0 (matches desktop).

Next:
  rover-mode                 # show mode (near|far)
  rover-env                  # print resolved env
  sudo systemctl enable --now rover-comms-bringup.service
  rover-verify               # check the link (desktop server must be up)

Drive test (moves the rover):
  rover-teleop-test 0.05 0.0 1.0
EOF
