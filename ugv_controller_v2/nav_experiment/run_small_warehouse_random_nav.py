"""Isaac launcher: baked-graph rover in small warehouse with random obstacles.

    isaacpy ugv_controller_v2/nav_experiment/run_small_warehouse_random_nav.py
    isaacpy ugv_controller_v2/nav_experiment/run_small_warehouse_random_nav.py --headless
    isaacpy ugv_controller_v2/nav_experiment/run_small_warehouse_random_nav.py --random-seed 1234
    isaacpy ugv_controller_v2/nav_experiment/run_small_warehouse_random_nav.py --obstacle-style props

This follows the v2 architecture: Python does not build navigation graphs and
does not drive the rover. The baked rover USD publishes ROS 2 once the sim plays;
this file composes a randomized small-warehouse USD generated by
``run_random_small_warehouse.py``. By default, Replicator is NOT active in the
live rover process.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path


SCRIPT_DIR = Path(__file__).resolve().parent
V2_ROOT = SCRIPT_DIR.parent
COMMON_DIR = V2_ROOT / "common"
for path in (SCRIPT_DIR, COMMON_DIR):
    if str(path) not in sys.path:
        sys.path.insert(0, str(path))

from random_small_warehouse_obstacles import (  # noqa: E402
    add_random_obstacle_args,
    obstacle_config_from_args,
    scatter_random_obstacles,
)
from run_random_small_warehouse import default_generated_usd  # noqa: E402
from run_baked_rover import asset_path, run  # noqa: E402


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Baked-graph rover in the small warehouse with Replicator obstacles."
    )
    parser.add_argument(
        "--headless",
        action="store_true",
        help="Run without the Isaac viewport (topics still publish).",
    )
    parser.add_argument(
        "--no-camera-topics",
        "--no_camera_topics",
        dest="camera_topics",
        action="store_false",
        default=True,
        help=(
            "Disable baked RGB/depth/camera_info publishers for lidar-only "
            "performance/debug sessions."
        ),
    )
    parser.add_argument(
        "--no-accessories",
        dest="accessories_enabled",
        action="store_false",
        default=True,
        help=(
            "Disable Isaac-window accessory controls (camera arm/lights). Useful "
            "when isolating PhysX runtime velocity-read errors; ROS topics and "
            "/cmd_vel driving are unaffected."
        ),
    )
    parser.add_argument(
        "--no-viewports",
        dest="viewports_enabled",
        action="store_false",
        default=True,
        help=(
            "Disable the extra visible arm/front camera viewports while keeping "
            "ROS camera/depth topics enabled. Useful when isolating SyntheticData "
            "or RTX post-process crashes."
        ),
    )
    parser.add_argument(
        "--environment-usd",
        type=Path,
        default=None,
        help=(
            "Use an explicit baked randomized warehouse USD. Defaults to the "
            "seed/count/style-specific file generated by run_random_small_warehouse.py."
        ),
    )
    parser.add_argument(
        "--live-replicator",
        action="store_true",
        help=(
            "Debug only: scatter obstacles with Replicator inside this live rover "
            "process instead of loading a pre-generated USD."
        ),
    )
    parser.add_argument(
        "--render-every-step",
        action="store_true",
        help=(
            "Diagnostic only: render every physics step instead of every fourth "
            "step. Slower, but useful when isolating PhysX/RTX timing errors."
        ),
    )
    parser.add_argument(
        "--disable-odom-graph",
        action="store_true",
        help=(
            "Diagnostic only: disable the baked odometry graph branch before "
            "play. This breaks Nav2 odom, but helps isolate PhysX velocity-read "
            "errors."
        ),
    )
    parser.add_argument(
        "--disable-joint-state-graph",
        action="store_true",
        help=(
            "Diagnostic only: disable the baked joint-state publisher graph "
            "before play."
        ),
    )
    parser.add_argument(
        "--disable-imu-graph",
        action="store_true",
        help="Diagnostic only: disable the baked IMU publisher graph before play.",
    )
    parser.add_argument(
        "--disable-lidar-graph",
        action="store_true",
        help="Diagnostic only: disable the baked lidar publisher graph before play.",
    )
    add_random_obstacle_args(parser)
    return parser.parse_args()


def _disabled_graph_paths(args: argparse.Namespace) -> tuple[str, ...]:
    graph_paths: list[str] = []
    if args.disable_odom_graph:
        graph_paths.append("/ROS2_Graphs/ROS_Odometry")
    if args.disable_joint_state_graph:
        graph_paths.extend(
            (
                "/ROS2_Graphs/ROS_JointState",
                "/ROS2_Graphs/ROS_JointStates",
                "/ROS2_Graphs/ROS_Joint_State",
            )
        )
    if args.disable_imu_graph:
        graph_paths.append("/ROS2_Graphs/ROS_IMU")
    if args.disable_lidar_graph:
        graph_paths.extend(
            (
                "/ROS2_Graphs/ROS_Lidar",
                "/ROS2_Graphs/ROS_LiDAR",
                "/ROS2_Graphs/ROS_RTX_Lidar",
            )
        )
    return tuple(graph_paths)


def main() -> int:
    args = _parse_args()
    obstacle_config = obstacle_config_from_args(args)
    environment_usd = args.environment_usd or default_generated_usd(args)

    def _scatter_before_play(*, simulation_app, stage) -> None:
        del stage
        authored = scatter_random_obstacles(simulation_app, **obstacle_config)
        print(
            f"[run_small_warehouse_random_nav] Authored {authored} static obstacles.",
            flush=True,
        )

    pre_play_setup = _scatter_before_play if args.live_replicator else None
    if not args.live_replicator:
        environment_usd = environment_usd.expanduser().resolve()
        if not environment_usd.exists():
            print(f"[run_small_warehouse_random_nav] Missing randomized warehouse USD: {environment_usd}")
            print("[run_small_warehouse_random_nav] Generate it first with:")
            print(
                "  isaacpy nav_experiment/run_random_small_warehouse.py "
                f"--random-seed {args.random_seed if args.random_seed is not None else 1234} "
                f"--random-obstacle-count {args.random_obstacle_count} "
                f"--obstacle-style {getattr(args, 'obstacle_style', 'primitives')} "
                f"--random-min-spacing {args.random_min_spacing} "
                f"--random-x-min {args.random_x_min} --random-x-max {args.random_x_max} "
                f"--random-y-min {args.random_y_min} --random-y-max {args.random_y_max}"
            )
            return 2

    return run(
        environment_usd=asset_path("small_warehouse.usd") if args.live_replicator else environment_usd,
        headless=args.headless,
        camera_topics=args.camera_topics,
        pre_play_setup=pre_play_setup,
        accessories_enabled=args.accessories_enabled,
        viewports_enabled=args.viewports_enabled,
        render_every_physics_step=args.render_every_step,
        disabled_graph_paths=_disabled_graph_paths(args),
    )


if __name__ == "__main__":
    raise SystemExit(main())
